import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {build} from 'vite';
await mkdir('tmp/permission-matrix-tests',{recursive:true});
await writeFile('tmp/permission-matrix-tests/entry.ts',"export * from '../../src/security/teamPermissionMatrix'; export {permissionCatalog} from '../../src/security/permissionCatalog';");
await build({configFile:false,build:{lib:{entry:'tmp/permission-matrix-tests/entry.ts',formats:['es'],fileName:'fixture'},outDir:'tmp/permission-matrix-tests',emptyOutDir:false,minify:false}});
const {permissionCatalog,effectivePermission,permissionLock,togglePermission,changedPermissions}=await import('../tmp/permission-matrix-tests/fixture.js');
const person=(id,parent)=>({id,nombre:id,superior_id:parent,activo:true,editable:true,permisos:permissionCatalog.map(d=>({clave:d.key,permitido:true,delegable:true,editable:true,efectivo:true}))});
let people=[person('boss',null),person('tech','boss'),person('helper','tech')];const base=structuredClone(people),def=permissionCatalog.find(d=>d.key==='foto.cargar');
assert(effectivePermission(people,people[2],def.key));
people=togglePermission(people,'boss',def.key,true);
assert(!effectivePermission(people,people[2],def.key),'Revoked delegation must limit descendants immediately');
assert.match(permissionLock(people,people[1],def,true,true),/superior/);
assert.equal(permissionLock(people,people[1],def,true,false),'','A limited explicit grant can be revoked');
people=togglePermission(people,'tech',def.key,false);
assert.match(permissionLock(people,people[1],def,true),/superior/,'New grants require a delegable parent');
assert.equal(people[1].permisos.find(p=>p.clave===def.key).delegable,false);
assert.equal(changedPermissions(base,people).length,2);
assert(base[0].permisos.find(p=>p.clave===def.key).delegable,'The source snapshot must remain intact');
people=structuredClone(base);people=togglePermission(people,'tech','foto.ver',false);
assert(!effectivePermission(people,people[1],'foto.cargar'),'Editing requires consultation');
assert(!effectivePermission(people,people[2],'foto.cargar'),'A parent without consultation cannot delegate editing');
assert.match(permissionLock(people,{...people[1],editable:false},def,true),/consulta/);
assert.match(permissionLock(people,people[1],def,false),/consulta/);
assert.match(permissionLock(people,people[1],permissionCatalog.find(d=>d.planned),true),/Próximamente/);
assert.match(permissionLock(people,people[1],permissionCatalog.find(d=>d.key==='empresa.crear'),true),/plataforma/);
console.log('Permission matrix: hierarchy, read prerequisites, revoked delegation, ghosts and immutable source passed');
